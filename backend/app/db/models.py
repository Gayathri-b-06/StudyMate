class ConceptMastery(Base):
    """
    Current EMA mastery score for one concept within a project.

    Keyed by (project_id, concept) where concept is the lowercased,
    stripped form of QuizAttempt.topic.  One row per concept per project —
    updated in-place on every quiz submission using an atomic UPSERT so
    concurrent submissions cannot produce a lost-update race condition.

    Formula (α = 0.4 exponential moving average):
        new_score = 0.4 × session_pct + 0.6 × old_score
    Initial old_score for a brand-new concept defaults to 50 (neutral prior).

    Isolation guarantee: the UNIQUE constraint on (project_id, concept) means
    "recursion" in Project A and "recursion" in Project B are always separate
    rows that can never share state.
    """

    __tablename__ = "concept_mastery"
    __table_args__ = (
        Index("ix_concept_mastery_project_concept", "project_id", "concept", unique=True),
        Index("ix_concept_mastery_project", "project_id"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    project_id: Mapped[str] = mapped_column(
        String, ForeignKey("projects.id", ondelete="CASCADE"), nullable=False
    )
    """Foreign key to the owning Project — cascade delete wipes mastery with the project."""

    concept: Mapped[str] = mapped_column(String, nullable=False)
    """Normalized concept name: topic.strip().lower(). Free-text, no canonical list."""

    score: Mapped[float] = mapped_column(nullable=False, default=50.0)
    """Current EMA mastery score, range 0.0–100.0."""

    attempt_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    """Total number of quiz attempts that have contributed to this score."""

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # relationships
    project: Mapped["Project"] = relationship("Project", back_populates="concept_masteries")


