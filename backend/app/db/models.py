class Document(Base):
    """
    Represents a PDF (or other source document) uploaded by the student.

    Each document stores metadata about the file and the path to the FAISS
    vector index built from its chunks. The vectorstore_path is used by the
    RAG retriever to load the correct index at query time.
    """

    __tablename__ = "documents"
    __table_args__ = (Index("ix_documents_thread_id", "thread_id"),)

    id: Mapped[str] = mapped_column(String, primary_key=True)
    """UUID string, generated by the application before insert."""

    thread_id: Mapped[str] = mapped_column(
        String, ForeignKey("threads.id", ondelete="CASCADE"), nullable=False
    )
    """Foreign key back to the owning thread."""

    filename: Mapped[str] = mapped_column(String, nullable=False)
    """Original filename as uploaded (e.g. 'lecture3.pdf')."""

    vectorstore_path: Mapped[str] = mapped_column(String, nullable=False)
    """
    Absolute (or workspace-relative) path to the directory containing the
    persisted FAISS index files (index.faiss + index.pkl).
    Convention: vectorstores/<thread_id>/<document_id>/
    """

    page_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    """Number of pages in the source PDF."""

    chunk_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    """Number of text chunks ingested into the vector store."""

    index_status: Mapped[str] = mapped_column(String, nullable=False, default="uploaded")
    """Async indexing state: 'uploaded' | 'indexing' | 'ready' | 'error'."""

    index_error: Mapped[str | None] = mapped_column(String, nullable=True)
    """Terminal indexing error message, when indexing fails."""

    uploaded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    """Timestamp set by the DB at INSERT time."""

    # relationships
    thread: Mapped["Thread"] = relationship("Thread", back_populates="documents")

    def __repr__(self) -> str:
        return f"<Document id={self.id!r} filename={self.filename!r}>"


