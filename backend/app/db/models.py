class Project(Base):
    """
    A focused learning journey inside a Space.

    A Project owns one or more Threads (conversation sessions), its uploaded
    Documents, quiz/flashcard history, and study-progress records.
    Deleting a Project cascades to all of its Threads → Documents.
    """

    __tablename__ = "projects"
    __table_args__ = (
        Index("ix_projects_space_id", "space_id"),
        Index("ix_projects_user_id", "user_id"),
    )

    id: Mapped[str] = mapped_column(String, primary_key=True)
    """UUID string, generated by the application before insert."""

    user_id: Mapped[str] = mapped_column(
        String, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, default=DEFAULT_USER_ID
    )
    """Owner user ID — matches owning Space's user_id."""

    space_id: Mapped[str] = mapped_column(
        String, ForeignKey("spaces.id", ondelete="CASCADE"), nullable=False
    )
    """Foreign key back to the owning Space."""

    name: Mapped[str] = mapped_column(String, nullable=False)
    """Human-readable project name (e.g. 'Week 3 Review')."""

    description: Mapped[str | None] = mapped_column(String, nullable=True)
    """Optional short description."""

    archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    """Soft-delete flag."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )

    # relationships
    owner: Mapped["User"] = relationship("User", back_populates="projects")
    space: Mapped["Space"] = relationship("Space", back_populates="projects")
    threads: Mapped[list["Thread"]] = relationship(
        "Thread", back_populates="project", cascade="all, delete-orphan"
    )
    user_memories: Mapped[list["UserMemory"]] = relationship(
        "UserMemory", back_populates="project", cascade="all, delete-orphan"
    )
    quiz_attempts: Mapped[list["QuizAttempt"]] = relationship(
        "QuizAttempt", back_populates="project", cascade="all, delete-orphan"
    )
    concept_masteries: Mapped[list["ConceptMastery"]] = relationship(
        "ConceptMastery", back_populates="project", cascade="all, delete-orphan"
    )
    concept_mastery_history: Mapped[list["ConceptMasteryHistory"]] = relationship(
        "ConceptMasteryHistory", back_populates="project", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Project id={self.id!r} name={self.name!r}>"


