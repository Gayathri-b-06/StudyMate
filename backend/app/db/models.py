class ConceptMasteryHistory(Base):
    """
    Append-only time-series of mastery score snapshots.

    One row is INSERTed after every quiz submission alongside the UPSERT to
    concept_mastery.  This table is never updated — only inserted into — so
    Growth Analysis can compute score trends over time without needing a
    second migration to retrofit history.
    """

    __tablename__ = "concept_mastery_history"
    __table_args__ = (
        Index("ix_cmh_project_concept_recorded", "project_id", "concept", "recorded_at"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    project_id: Mapped[str] = mapped_column(
        String, ForeignKey("projects.id", ondelete="CASCADE"), nullable=False
    )
    concept: Mapped[str] = mapped_column(String, nullable=False)
    score: Mapped[float] = mapped_column(nullable=False)
    """EMA score at the moment this snapshot was recorded."""

    recorded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    project: Mapped["Project"] = relationship("Project", back_populates="concept_mastery_history")
