"""
db/models.py
============
SQLAlchemy 2.0 ORM model definitions for StudyMate.

Tables
------
- spaces       : A broad learning area (e.g. "DSA Prep", "System Design").
- projects     : A focused learning journey inside a Space.
- threads      : A LangGraph conversation session inside a Project.
- documents    : A PDF uploaded by the student, linked to a thread.
- study_log    : An audit trail of study events.
- topics_cache : Cached extracted document topics.
- user_memories: Structured weak-topic / preference facts, scoped to a project.
- quiz_attempts: Append-only record of completed quiz scores, scoped to a project.

Design notes
------------
- SQLAlchemy 2.0 `Mapped` / `mapped_column` API for full static-type safety.
- All primary keys are string UUIDs (app-generated) for portability.
- `ondelete="CASCADE"` on FKs means deleting a parent row automatically
  removes all child rows at the DB level.
- Space/Project have no `owner_id` yet — that column will be added as nullable
  in a future auth migration. See Known Limitations in the implementation plan.
"""

from datetime import datetime
from enum import Enum

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum as SqlEnum,
    ForeignKey,
    Integer,
    String,
    func,
    Index,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.config import DEFAULT_USER_ID


# ---------------------------------------------------------------------------
# Declarative base
# ---------------------------------------------------------------------------

class Base(DeclarativeBase):
    """Shared declarative base for all StudyMate ORM models."""
    pass


# ---------------------------------------------------------------------------
# users & user_sessions
# ---------------------------------------------------------------------------

class User(Base):
    """
    An authenticated StudyMate student or admin account.
    """
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(String, primary_key=True)
    email: Mapped[str] = mapped_column(String, unique=True, nullable=False, index=True)
    name: Mapped[str] = mapped_column(String, nullable=False)
    password_hash: Mapped[str] = mapped_column(String, nullable=False)
    salt: Mapped[str] = mapped_column(String, nullable=False)
    role: Mapped[str] = mapped_column(String, nullable=False, default="student")
    is_demo: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # relationships
    spaces: Mapped[list["Space"]] = relationship(
        "Space", back_populates="owner", cascade="all, delete-orphan"
    )
    projects: Mapped[list["Project"]] = relationship(
        "Project", back_populates="owner", cascade="all, delete-orphan"
    )
    sessions: Mapped[list["UserSession"]] = relationship(
        "UserSession", back_populates="user", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<User id={self.id!r} email={self.email!r} role={self.role!r}>"


class UserSession(Base):
    """
    Active authentication session for a User.
    """
    __tablename__ = "user_sessions"

    token: Mapped[str] = mapped_column(String, primary_key=True)
    user_id: Mapped[str] = mapped_column(
        String, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # relationship
    user: Mapped["User"] = relationship("User", back_populates="sessions")

    def __repr__(self) -> str:
        return f"<UserSession token=... user_id={self.user_id!r}>"


# ---------------------------------------------------------------------------
# spaces
# ---------------------------------------------------------------------------

class Space(Base):
    """
    A broad learning area grouping one or more Projects.

    Examples: "DSA Prep", "System Design", "Linear Algebra".
    Deleting a Space cascades to its Projects → Threads → Documents.
    """

    __tablename__ = "spaces"
    __table_args__ = (Index("ix_spaces_user_id", "user_id"),)

    id: Mapped[str] = mapped_column(String, primary_key=True)
    """UUID string, generated by the application before insert."""

    user_id: Mapped[str] = mapped_column(
        String, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, default=DEFAULT_USER_ID
    )
    """Owner user ID — enforces user isolation."""

    name: Mapped[str] = mapped_column(String, nullable=False)
    """Human-readable label shown in the sidebar."""

    description: Mapped[str | None] = mapped_column(String, nullable=True)
    """Optional tagline for the space."""

    archived: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    """Soft-delete flag. Archived spaces are hidden from the sidebar."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )

    # relationships
    owner: Mapped["User"] = relationship("User", back_populates="spaces")
    projects: Mapped[list["Project"]] = relationship(
        "Project", back_populates="space", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Space id={self.id!r} name={self.name!r} user_id={self.user_id!r}>"


