class Thread(Base):
    """
    A LangGraph conversation session within a Project.

    A Thread groups a set of uploaded Documents and the chat history
    associated with them. Deleting a Thread cascades to its Documents
    and StudyLog rows.

    Note: thread_id is the LangGraph conversation key (baked into checkpoints)
    and is intentionally kept separate from project_id.
    """

    __tablename__ = "threads"
    __table_args__ = (Index("ix_threads_project_id", "project_id"),)

    id: Mapped[str] = mapped_column(String, primary_key=True)
    """UUID string, generated by the application before insert."""

    project_id: Mapped[str] = mapped_column(
        String, ForeignKey("projects.id", ondelete="CASCADE"), nullable=False
    )
    """Foreign key back to the owning Project."""

    title: Mapped[str] = mapped_column(String, nullable=False)
    """Human-readable label shown in the sidebar (e.g. 'CS101 Week 3')."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )

    # relationships
    project: Mapped["Project"] = relationship("Project", back_populates="threads")
    documents: Mapped[list["Document"]] = relationship(
        "Document", back_populates="thread", cascade="all, delete-orphan"
    )
    study_log: Mapped[list["StudyLog"]] = relationship(
        "StudyLog", back_populates="thread", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Thread id={self.id!r} title={self.title!r}>"


